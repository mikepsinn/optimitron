export const GOVERNMENT_ISO3_TO_ISO2 = Object.fromEntries(
  Object.entries(GOVERNMENT_ISO2_TO_ISO3).map(([iso2, iso3]) => [iso3, iso2]),
) as Record<string, string>;

export function getGovernmentIso3(code: string) {
  return GOVERNMENT_ISO2_TO_ISO3[code.trim().toUpperCase()] ?? null;
}

export function getGovernmentCodeForIso3(iso3: string) {
  return GOVERNMENT_ISO3_TO_ISO2[iso3.trim().toUpperCase()] ?? null;
}

export function getGovernmentDisplayName(code: string) {
  const normalizedCode = code.trim().toUpperCase();
  if (!normalizedCode) {
    return null;
  }

  return (
    REGION_NAME_OVERRIDES[normalizedCode] ??
    GOVERNMENT_REGION_DISPLAY_NAMES.of(normalizedCode) ??
    null
  );
}
